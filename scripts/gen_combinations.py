# -*- coding: utf-8 -*-
from pathlib import Path

faces = [
    "Заклинание превращения в одного из",
    "Расскажи чем испугать всех",
    "Подбери прозвище для кого-то из",
    "Придумай страшное проклятие для",
    "Комплимент, который вгонит в краску",
    "Подскажи как отшить",
    "Почему стоит избегать",
    "Какая польза от",
    "Назови тайную слабость",
    "Какое наказание ждёт в аду для",
    "Чем оскорбить любого из",
    "Какой подлянки ждать от",
    "Лучший подарок для",
    "Чем соблазнить",
]
backs = [
    "конченных интровертов",
    "здесь присутствующих",
    "ухоженных дровосеков",
    "твоих бывших",
    "соседей сверху",
    "любителей настолок",
    "самокатчиков",
    "бабок у подъезда",
    "чемпионов френдзоны",
    "пузатых скуфов",
    "милф",
    "душнил",
    "нейросетей",
    "очкариков",
]

lines = [
    "# Все сочетания запросов",
    "",
    f"Лицевая + оборотная. Всего: {len(faces) * len(backs)} ({len(faces)} × {len(backs)}).",
    "",
]
n = 0
for i, f in enumerate(faces, 1):
    lines.append(f"## {i}. {f}")
    lines.append("")
    for b in backs:
        n += 1
        lines.append(f"{n}. {f} {b}")
    lines.append("")

Path(__file__).resolve().parents[1].joinpath("request-combinations.md").write_text(
    "\n".join(lines) + "\n", encoding="utf-8"
)
print(f"faces={len(faces)} backs={len(backs)} combinations={n}")
