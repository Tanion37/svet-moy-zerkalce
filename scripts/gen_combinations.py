# -*- coding: utf-8 -*-
from pathlib import Path

faces = [
    "Произнеси заклинание превращения в",
    "Расскажи чем испугать всех",
    "Подбери прозвище для любого из",
    "Придумай страшное проклятие для",
    "Составь комплимент, который вгонит в краску",
    "Подскажи как отшить",
    "Что пригодится для пранка над любым из",
    "Какую пользу можно ожидать от",
    "Назови тайную слабость",
    "Какое наказание ждёт в аду для",
    "Чем оскорбить любого из",
    "Какой подлянки можно ожидать от",
    "Лучший подарок",
    "Чем соблазнить",
]
backs = [
    "конченных интровертов",
    "здесь присутствующих",
    "ухоженных дровосеков",
    "твоих бывших",
    "соседей сверху",
    "любителей настолок",
    "самокатчиков",
    "бабок у подъезда",
    "чемпионов френдзоны",
    "пузатых скуфов",
    "милф",
    "душнил",
    "нейросетей",
]

# Для печати 14 карт: 14-й оборот = повтор последнего
PRINT_BACKS = backs + [backs[-1]]

lines = [
    "# Все сочетания запросов",
    "",
    f"Лицевая + оборотная. Всего: {len(faces) * len(backs)} ({len(faces)} × {len(backs)}).",
    "",
    f"Уникальных оборотов: {len(backs)}. На печати 14-й карты запроса оборот "
    f"«{backs[-1]}» повторяется (пулы лицевых выровнены до {len(faces)}).",
    "",
]
n = 0
for i, f in enumerate(faces, 1):
    lines.append(f"## {i}. {f}")
    lines.append("")
    for b in backs:
        n += 1
        lines.append(f"{n}. {f} {b}")
    lines.append("")

Path(__file__).resolve().parents[1].joinpath("request-combinations.md").write_text(
    "\n".join(lines) + "\n", encoding="utf-8"
)
print(f"faces={len(faces)} backs={len(backs)} combinations={n} print_backs={len(PRINT_BACKS)}")
